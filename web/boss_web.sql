CREATE TABLE IF NOT EXISTS boss_web_config (
 boss_key VARCHAR(100) NOT NULL PRIMARY KEY,
 name VARCHAR(255) NOT NULL,
 hp INT NOT NULL, damage INT NOT NULL, rest_seconds INT NOT NULL,
 enabled TINYINT NOT NULL DEFAULT 1, customized TINYINT NOT NULL DEFAULT 0,
 map_ids TEXT NOT NULL, head_id INT NOT NULL DEFAULT 0, online_count INT NOT NULL DEFAULT 0,
 can_spawn TINYINT NOT NULL DEFAULT 0,
 current_locations TEXT NULL,
 lifetime_seconds INT NULL, timing_state LONGTEXT NULL,
 heartbeat DATETIME NULL, applied_at DATETIME NULL
);
CREATE TABLE IF NOT EXISTS boss_web_command (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 boss_key VARCHAR(100) NOT NULL, requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 delay_seconds INT NOT NULL DEFAULT 0,
 completed_at DATETIME NULL, result VARCHAR(255) NULL
);
CREATE TABLE IF NOT EXISTS boss_web_drop_config (
 boss_key VARCHAR(100) NOT NULL PRIMARY KEY,
 mode VARCHAR(16) NOT NULL DEFAULT 'original', items LONGTEXT NOT NULL,
 revision BIGINT NOT NULL DEFAULT 1, applied_revision BIGINT NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, applied_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
